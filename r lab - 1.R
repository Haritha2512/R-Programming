num_vector <- c(10, 20, 30, 40, 50)

char_vector <- c("Apple", "Banana", "Mango")

log_vector <- c(TRUE, FALSE, TRUE, FALSE)

print("Numeric Vector:")
print(num_vector)

print("Character Vector:")
print(char_vector)

print("Logical Vector:")
print(log_vector)

print("Data Type of Numeric Vector:")
print(typeof(num_vector))

print("Data Type of Character Vector:")
print(typeof(char_vector))

print("Data Type of Logical Vector:")
print(typeof(log_vector))
